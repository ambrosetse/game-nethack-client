#!/usr/bin/env python3
"""Generate the core-text translation tables from tools/core_text_table.txt.

    python3 tools/build_core_text.py [TABLE] [JSON_OUT] [INC_OUT]

The table is pipe separated: english|zh_TW|zh_CN|ko|ja.  Lines starting with
'#' and blank lines are ignored.  The English column is stored with its
whitespace collapsed (lookups normalise the text the same way).  Outputs:

  godot/locale/core_text.json        read by godot/scripts/core/core_text.gd
  native/bridge/core_text_table.inc  compiled into native/bridge/core_text.cpp

Both carry the same rows in the same order, so the GDScript fallback and the
native translator give identical results.  check_translations.py verifies the
outputs are current.
"""

import json
import os
import re
import sys

LANGS = ["zh_TW", "zh_CN", "ko", "ja"]
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_TABLE = os.path.join(HERE, "core_text_table.txt")
DEFAULT_JSON = os.path.join(HERE, "..", "godot", "locale", "core_text.json")
DEFAULT_INC = os.path.join(HERE, "..", "native", "bridge", "core_text_table.inc")
PLACEHOLDER_RE = re.compile(r"\{(\d+)(:t)?\}")


def normalise(s):
    return " ".join(s.split())


def placeholders(s):
    """The set of placeholder numbers in s ({1} and {1:t} both count as 1)."""
    return sorted(int(m.group(1)) for m in PLACEHOLDER_RE.finditer(s))


def check_pattern(english):
    """Problems with an English pattern: captures must be separated by text."""
    problems = []
    parts = PLACEHOLDER_RE.split(english)
    # split gives [text, num, t, text, num, t, ..., text]
    texts = parts[0::3]
    for i, t in enumerate(texts[1:-1], 1):
        if t == "":
            problems.append("placeholders %d and %d are adjacent" % (i, i + 1))
    nums = placeholders(english)
    if len(set(nums)) != len(nums):
        problems.append("placeholder used twice")
    return problems


def read_table(path):
    """[(english, [zh_TW, zh_CN, ko, ja])], raising ValueError on bad rows."""
    rows = []
    seen = set()
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            cols = line.split("|")
            where = "%s:%d" % (path, n)
            if len(cols) != len(LANGS) + 1:
                raise ValueError("%s: expected %d columns, got %d"
                                 % (where, len(LANGS) + 1, len(cols)))
            english = normalise(cols[0])
            values = [c.strip() for c in cols[1:]]
            if not english:
                raise ValueError("%s: empty English text" % where)
            if english in seen:
                raise ValueError("%s: duplicate entry %r" % (where, english))
            seen.add(english)
            for lang, v in zip(LANGS, values):
                if not v:
                    raise ValueError("%s: empty %s translation" % (where, lang))
                if placeholders(v) != sorted(set(placeholders(english))):
                    raise ValueError("%s: %s placeholders %s do not match %s"
                                     % (where, lang, placeholders(v), placeholders(english)))
                if ":t}" in v:
                    raise ValueError("%s: %s uses {n:t}; mark :t in English only" % (where, lang))
            for p in check_pattern(english):
                raise ValueError("%s: %s" % (where, p))
            rows.append((english, values))
    return rows


def render_json(rows):
    # one row per line keeps diffs readable
    body = ",\n".join(json.dumps([e] + v, ensure_ascii=False) for e, v in rows)
    return '{"langs": %s, "rows": [\n%s\n]}\n' % (json.dumps(LANGS), body)


def c_string(s):
    out = []
    for ch in s.encode("utf-8"):
        c = chr(ch)
        if c in '"\\':
            out.append("\\" + c)
        elif 32 <= ch < 127:
            out.append(c)
        else:
            # octal escapes cannot swallow the following characters
            out.append("\\%03o" % ch)
    return '"' + "".join(out) + '"'


def render_inc(rows):
    lines = [
        "/* Generated by tools/build_core_text.py from tools/core_text_table.txt.",
        " * Do not edit; edit the table and regenerate. */",
        "/* english, zh_TW, zh_CN, ko, ja */",
    ]
    for e, v in rows:
        lines.append("{%s}," % ", ".join(c_string(s) for s in [e] + v))
    return "\n".join(lines) + "\n"


def outputs(table):
    rows = read_table(table)
    return rows, render_json(rows), render_inc(rows)


def build(table, json_out, inc_out):
    rows, js, inc = outputs(table)
    for path, text in ((json_out, js), (inc_out, inc)):
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return rows


def main(argv):
    table = argv[1] if len(argv) > 1 else DEFAULT_TABLE
    json_out = argv[2] if len(argv) > 2 else DEFAULT_JSON
    inc_out = argv[3] if len(argv) > 3 else DEFAULT_INC
    rows = build(table, json_out, inc_out)
    print("%d rows -> %s, %s" % (len(rows), os.path.basename(json_out), os.path.basename(inc_out)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
